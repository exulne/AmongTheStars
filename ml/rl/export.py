"""Pack every generation of a run into src/ml/warWeights.ts for the browser.

    python3 ml/rl/export.py [--run realpolitik]

Each layer of each generation is quantised to int8 with its own scale: about
19 KB a generation instead of 75 KB, and the policies decide the same way to
within sampling noise.
"""
import argparse, base64, json, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# (out, in) of each layer, the order of warNet.ts LAYERS
LAYERS = [(128, 32), (64, 128), (1, 64), (4, 64), (64, 86), (8, 64)]

ap = argparse.ArgumentParser(); ap.add_argument('--run', default='realpolitik'); a = ap.parse_args()
ck = os.path.join(ROOT, 'ml/rl/runs', a.run, 'ckpt')
gens = sorted(f for f in os.listdir(ck) if f.startswith('gen_'))
scales, q = [], []
for g in gens:
    x = np.fromfile(os.path.join(ck, g), np.float32); k = 0
    for o, i in LAYERS:
        n = o * i + o
        part = x[k:k + n]; k += n
        s = float(np.abs(part).max()) / 127 or 1.0
        scales.append(s); q.append(np.clip(np.round(part / s), -127, 127).astype(np.int8))
    assert k == len(x)
blob = base64.b64encode(np.concatenate(q).tobytes()).decode()
body = json.dumps({'run': a.run, 'gens': len(gens), 'scales': [round(s, 9) for s in scales], 'q': blob})
out = os.path.join(ROOT, 'src/ml/warWeights.ts')
open(out, 'w').write(f'// Generated by ml/rl/export.py from run "{a.run}". Do not edit.\nexport default {body};\n')
print(f'wrote {out}: {len(gens)} generations, {len(body) // 1024} KB')
