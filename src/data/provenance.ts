/** How a single value came to be. */
export type ValueBasis = 'observed' | 'reported' | 'estimated' | 'simulated';

export type Quality = 'high' | 'medium' | 'low' | 'unknown';

export interface Provenance {
  organization: string;
  url: string;
  /** ISO 8601 UTC: when the value was fetched or, for curated records, checked against the source */
  retrieved: string;
  /** dataset or API version, or signature, when the source states one */
  version?: string;
  /** observation or element-set epoch (ISO 8601 UTC) when it differs from retrieval */
  epoch?: string;
  basis: ValueBasis;
  quality: Quality;
  /** free-text caveat: what is uncertain, what was inferred */
  note?: string;
}

/** A number with its unit, range and provenance. low ≤ nominal ≤ high. */
export interface Ranged {
  low: number; nominal: number; high: number;
  unit: string;
  basis: ValueBasis;
  source: string;
}

export function ranged(nominal: number, low: number, high: number, unit: string, basis: ValueBasis, source: string): Ranged {
  if (!(low <= nominal && nominal <= high)) throw new Error(`range out of order: ${low} ≤ ${nominal} ≤ ${high} (${source})`);
  return { low, nominal, high, unit, basis, source };
}

export const DISCLAIMER = 'Educational and strategic simulation. Not an operational spaceflight, collision-avoidance, reentry-safety or planetary-defense tool.';

/** HTML badge for a classification (the desk's CSS styles .cls-badge). */
export function classBadge(c: Classification): string {
  const s = CLASS_STYLE[c];
  return `<span class="cls-badge" style="--cls:${s.color}" title="${s.label}: ${s.meaning}">${s.badge}</span>`;
}
