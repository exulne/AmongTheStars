// Facts versus simulations. Every object, mission, facility, close approach,
// probability and impact the app shows carries exactly one Classification and a
// Provenance record, and the UI draws each class differently (colour, line
// style, badge), so a simulated future satellite never looks like an observed
// one and an announced plan never looks like a flown mission.
// Methodology: research/orbits-and-impacts.md.

export const CLASSIFICATIONS = [
  'historical', 'active', 'scheduled', 'contracted', 'announced', 'hypothetical', 'simulated',
] as const;
export type Classification = (typeof CLASSIFICATIONS)[number];

export interface ClassStyle {
  label: string;
  /** one line for a tooltip */
  meaning: string;
  /** badge and point colour (validated categorical slots on the dark desk) */
  color: string;
  /** SVG stroke-dasharray for lines and shells drawn in this class ('' = solid) */
  dash: string;
  /** three.js point opacity: observed solid, plans fainter, simulations faintest */
  alpha: number;
  /** short badge text */
  badge: string;
}

