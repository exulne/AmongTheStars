// Fits the compact thermosphere (src/orbit/thermosphere.ts) to NRLMSIS 2.0
// reference outputs and writes src/orbit/thermosphereFit.ts with the fitted
// coefficients and validation statistics (training rows, held-out rows, and a
// cross-check against USSA76 above the reference data's 500 km ceiling).
//   node scripts/msis-calibrate.ts
// If pymsis is available, research/data can hold a denser MSIS table in the
// same column format and this script will use it unchanged.

import { readFileSync, writeFileSync } from 'node:fs';
import { speciesAt, thermoDensity, ussa76, type AtmoInput } from '../src/orbit/thermosphere.ts';
import { THERMO_FIT } from '../src/orbit/thermosphereFit.ts';

const FILE = 'research/data/nrlmsis2.0_test_ref_dp.txt';
interface Row { q: AtmoInput; rho: number; n: { N2: number; O2: number; O: number; He: number } }
const rows: Row[] = [];
for (const line of readFileSync(FILE, 'utf8').split('\n').slice(1)) {
  const c = line.trim().split(/\s+/).map(Number);
  if (c.length < 19 || c[2] < 120) continue;
  const doy = c[0] % 1000;
  rows.push({
    q: { altKm: c[2], latDeg: c[3], lstH: c[5], f107a: c[6], f107: c[7], ap: c[8], doy },
    rho: c[14] * 1000, // g/cm³ → kg/m³
    n: { He: c[9] * 1e6, O: c[10] * 1e6, N2: c[11] * 1e6, O2: c[12] * 1e6 }, // cm⁻³ → m⁻³
  });
}
const train = rows.filter((_, i) => i % 3 !== 2), hold = rows.filter((_, i) => i % 3 === 2);

const x0 = [...THERMO_FIT.coeffs];
// typical scale of each coefficient, for the simplex and the weak prior
const scale = [40, 0.6, 0.6, 0.1, 2, 0.5, 30, 0.006, 0.3, 0.1, 0.3, 0.3, 0.1, 0.3, 0.2, 0.3, 0.3, 1, 0.2];
const IDX = ['N2', 'O2', 'O', 'He'] as const;
const lg = Math.log10;

function loss(x: number[], set: Row[]): number {
  if (x[7] <= 0.002 || x[3] < 0 || x[3] > 0.6 || x[6] < 250 || x[6] > 500) return 1e9;
  let s = 0;
  for (const r of set) {
    const m = thermoDensity(x, r.q);
    s += (lg(m) - lg(r.rho)) ** 2;
    const n = speciesAt(x, r.q, r.q.altKm);
    IDX.forEach((k, i) => { if (r.n[k] > 1e6) s += 0.15 * (lg(n[i]) - lg(r.n[k])) ** 2; });
  }
  // weak prior toward the physical starting values (keeps unconstrained terms sane)
  let p = 0;
  for (let i = 0; i < x.length; i++) p += ((x[i] - x0[i]) / scale[i]) ** 2;
  return s / set.length + 0.002 * p;
}

function nelderMead(f: (x: number[]) => number, start: number[], step: number[], iters: number): number[] {
  const n = start.length;
  let simplex = [start, ...start.map((_, i) => start.map((v, j) => (i === j ? v + step[j] : v)))].map((x) => ({ x, f: f(x) }));
  for (let k = 0; k < iters; k++) {
    simplex.sort((a, b) => a.f - b.f);
    const best = simplex[0], worst = simplex[n], second = simplex[n - 1];
    const c = start.map((_, j) => simplex.slice(0, n).reduce((s, v) => s + v.x[j], 0) / n);
    const at = (t: number) => c.map((v, j) => v + t * (worst.x[j] - v));
    const r = at(-1), fr = f(r);
    if (fr < best.f) { const e = at(-2), fe = f(e); simplex[n] = fe < fr ? { x: e, f: fe } : { x: r, f: fr }; }
    else if (fr < second.f) simplex[n] = { x: r, f: fr };
    else {
      const ct = fr < worst.f ? at(-0.5) : at(0.5), fc = f(ct);
      if (fc < Math.min(fr, worst.f)) simplex[n] = { x: ct, f: fc };
      else simplex = simplex.map((v, i) => (i === 0 ? v : (() => { const x = v.x.map((y, j) => best.x[j] + 0.5 * (y - best.x[j])); return { x, f: f(x) }; })()));
    }
  }
  simplex.sort((a, b) => a.f - b.f);
  return simplex[0].x;
}

let x = x0;
for (let round = 0; round < 6; round++) {
  x = nelderMead((v) => loss(v, train), x, scale.map((s) => s * 0.5), 4000);
  console.log(`round ${round}: training loss ${loss(x, train).toFixed(5)}`);
}

function stats(set: Row[]) {
  const e = set.map((r) => lg(thermoDensity(x, r.q)) - lg(r.rho));
  const bias = e.reduce((a, b) => a + b, 0) / e.length;
  return { n: e.length, rmsLog10: Math.sqrt(e.reduce((a, b) => a + b * b, 0) / e.length), biasLog10: bias, maxAbsLog10: Math.max(...e.map(Math.abs)) };
}
const tr = stats(train), ho = stats(hold);
// USSA76 corresponds to moderate activity (F10.7 ≈ 150, Ap ≈ 4), mid-latitude mean
const ussa = [150, 200, 300, 400, 500, 600, 700, 800, 900, 1000].map((altKm) => {
  let s = 0, k = 0;
  for (let h = 0; h < 24; h += 3) for (const lat of [0, 30, -30, 45, -45]) { s += thermoDensity(x, { altKm, f107: 150, f107a: 150, ap: 4, latDeg: lat, lstH: h + 1.5, doy: 80 }); k++; }
  return { altKm, ratio: Number((s / k / ussa76(altKm)).toFixed(3)) };
});
console.log('training', tr, '\nheld out', ho, '\nmodel/USSA76', ussa.map((u) => `${u.altKm}:${u.ratio}`).join(' '));

const out = `// Generated by scripts/msis-calibrate.ts. Do not edit by hand.
export const THERMO_FIT = {
  version: '${new Date().toISOString().slice(0, 10)}',
  reference: 'NRLMSIS 2.0 reference outputs (msis2.0_test_ref_dp.txt, via SWxTREC/pymsis, MIT licence)',
  names: ${JSON.stringify(THERMO_FIT.names)},
  coeffs: ${JSON.stringify(x.map((v) => Number(v.toPrecision(6))))} as readonly number[],
  train: { n: ${tr.n}, rmsLog10: ${tr.rmsLog10.toFixed(4)}, biasLog10: ${tr.biasLog10.toFixed(4)} },
  holdout: { n: ${ho.n}, rmsLog10: ${ho.rmsLog10.toFixed(4)}, biasLog10: ${ho.biasLog10.toFixed(4)}, maxAbsLog10: ${ho.maxAbsLog10.toFixed(4)} },
  ussa76: ${JSON.stringify(ussa)} as { altKm: number; ratio: number }[],
};
`;
writeFileSync('src/orbit/thermosphereFit.ts', out);
console.log('wrote src/orbit/thermosphereFit.ts');
